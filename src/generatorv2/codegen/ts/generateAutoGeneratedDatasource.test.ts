import { runInNewContext } from "node:vm";
import ts from "typescript";
import { DataStoreHandler } from "../../../migration/dataStore.js";
import { StoreMigrator } from "../../../migration/front/storeMigrator.js";
import { QExpr as qe } from "../../../runtime/dsl/factory.js";
import { EntityNode } from "../../nodes/entityNode.js";
import { generateAutoGeneratedDatasource } from "./generateAutoGeneratedDatasource.js";

function setup(
  options: {
    composite?: boolean;
    unsigned?: boolean;
    unsafe?: boolean;
    defaults?: boolean;
  } = {},
) {
  const store = StoreMigrator.deserialize({ tables: [] });
  store.createTable("record", (table) => {
    const id = table.column("record_id").bigInt().fieldName("id");
    if (options.unsigned) id.unsigned();
    if (!options.composite) id.primary().autoIncrement();
    if (options.composite) {
      table.column("tenant_id").int().fieldName("tenantId");
      table.setPrimaryKey("record_id", "tenant_id");
    }
    if (options.defaults !== false) {
      table
        .column("total")
        .bigInt()
        .default(
          options.unsafe ? Number.MAX_SAFE_INTEGER + 1 : "9007199254740993",
        );
      table
        .column("amount")
        .decimal(38, 18)
        .default("12345678901234567890.123456789012345678");
      table.column("title").varchar(40).default("O'Reilly");
      table.column("optional").varchar(40).nullable().default(null);
      table.createdAt();
    }
  });
  const ds = new DataStoreHandler(store.serialize());
  const entity = new EntityNode(ds, ds.table("record"));
  const first = jest.fn();
  const clock = jest.fn(() => "2026-01-01 00:00:00");
  const exports: Record<
    string,
    new () => {
      getDefaultValueString(): Record<string, unknown>;
      findByIdAndTenantId(...args: unknown[]): unknown;
      autoIncrementColumn?: string;
    }
  > = {};
  runInNewContext(
    ts.transpileModule(generateAutoGeneratedDatasource(entity).toString(), {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2022,
      },
    }).outputText,
    {
      exports,
      require: (name: string) => {
        if (name === "sasat") return { qe, getCurrentDateTimeString: clock };
        if (/baseDBDataSource(\.js)?$/.test(name))
          return {
            BaseDBDataSource: class {
              first = first;
            },
          };
        throw new Error(`Unexpected generated import: ${name}`);
      },
    },
  );
  return {
    datasource: new exports[entity.name.generatedDataSourceName()](),
    first,
    clock,
  };
}

test("generated defaults preserve exact numeric types, null and quotes and recompute timestamps", () => {
  const { datasource: ds, clock } = setup();
  const values = ds.getDefaultValueString();
  expect(values).toEqual({
    total: 9007199254740993n,
    amount: "12345678901234567890.123456789012345678",
    title: "O'Reilly",
    optional: null,
    createdAt: "2026-01-01 00:00:00",
  });
  clock.mockReturnValueOnce("2026-01-02 00:00:00");
  expect(ds.getDefaultValueString().createdAt).toBe("2026-01-02 00:00:00");
});
test("unsafe bigint defaults fail generation before any code is emitted", () => {
  expect(() => setup({ unsafe: true })).toThrow(
    "BigInt defaults must be exact integers",
  );
});
test.each([false, true])(
  "bigint auto-increment metadata retains unsigned=%s",
  (unsigned) => {
    const { datasource: ds } = setup({ unsigned, defaults: false });
    expect(ds).toMatchObject({
      autoIncrementColumn: "id",
      autoIncrementBigInt: true,
      autoIncrementUnsigned: unsigned,
      primaryKeys: ["record_id"],
      identifyFields: ["id"],
    });
    expect(ds.getDefaultValueString()).toEqual({});
  },
);
test.each([undefined, "records_alias"])(
  "generated composite lookup preserves aliases, filters, context and input: %s",
  (alias) => {
    const { datasource: ds, first } = setup({ composite: true });
    const fields = alias ? { tableAlias: alias, fields: ["id"] } : undefined;
    const where = qe.eq(qe.field(alias ?? "t0", "active"), qe.value(1));
    const options = Object.freeze({ where });
    const context = { tenant: 3 };
    const expected = { id: 9n, tenantId: 3 };
    first.mockReturnValue(expected);
    expect(ds.findByIdAndTenantId(9n, 3, fields, options, context)).toBe(
      expected,
    );
    expect(first).toHaveBeenCalledWith(
      fields,
      {
        where: qe.and(
          qe.eq(qe.field(alias ?? "t0", "record_id"), qe.value(9n)),
          qe.eq(qe.field(alias ?? "t0", "tenant_id"), qe.value(3)),
          where,
        ),
      },
      context,
    );
    expect(options.where).toBe(where);
    expect(ds.autoIncrementColumn).toBeUndefined();
  },
);
